"""Phase 04: render the generated tables of BAKEOFF.md from BAKEOFF_RESULTS.json and evidence/wheel_availability.json.

wheel_availability.json is built from the PyPI JSON of each exact version (cached outside the repository by build_lock.py and
the first PyPI reads) when that cache exists; otherwise the committed file is used as is.

    python render_tables.py BAKEOFF.md BAKEOFF_RESULTS.json
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
EV = HERE.parent / "evidence"
CACHE = [Path("/home/claude/pi_research/p04/pypi_versions"), Path("/home/claude/pi_research/p04_pypi")]
MARK = "<!-- tables below are generated by prototypes/render_tables.py; do not edit by hand -->"
PACKAGES = [("numpy", "2.5.3"), ("pandas", "3.0.5"), ("scipy", "1.18.1"), ("scikit-learn", "1.9.1"), ("lightgbm", "4.7.0"),
            ("mapie", "1.6.0"), ("purgedcv", "0.1.11"), ("river", "0.26.1"), ("lifelines", "0.30.3"), ("pandera", "0.34.1"),
            ("mesa", "3.5.1"), ("venn-abers", "1.5.4"), ("statsmodels", "0.15.0"), ("arch", "8.0.0"), ("crepes", "0.9.1"),
            ("interpret-core", "0.7.8")]
PLAT = {"linux": r"(cp313-cp313|cp3\d+-abi3|py3-none)-[^-]*manylinux[^-]*x86_64\.whl$|py3-none-any\.whl$",
        "windows": r"(cp313-cp313|cp3\d+-abi3|py3-none)-win_amd64\.whl$|py3-none-any\.whl$",
        "macos_arm64": r"(cp313-cp313|cp3\d+-abi3|py3-none)-macosx_[0-9_]+_(arm64|universal2)\.whl$|py3-none-any\.whl$"}


def wheel_availability() -> dict:
    out = {}
    for name, ver in PACKAGES:
        doc = None
        for c in CACHE:
            for f in (c / f"{name}-{ver}.json", c / f"{name}.json"):
                if f.exists():
                    d = json.loads(f.read_text())
                    if d.get("info", {}).get("version") == ver:
                        doc = d
                        break
            if doc:
                break
        if doc is None:
            continue
        files = [u["filename"] for u in doc["urls"]]
        out[f"{name}=={ver}"] = {p: any(re.search(rx, f) for f in files) for p, rx in PLAT.items()}
        out[f"{name}=={ver}"]["sdist_only"] = all(f.endswith(".tar.gz") for f in files)
        out[f"{name}=={ver}"]["requires_python"] = doc["info"].get("requires_python")
    return out


def main(md: str, results: str) -> None:
    r = json.loads(Path(results).read_text())
    wa_path = EV / "wheel_availability.json"
    wa = wheel_availability()
    if len(wa) == len(PACKAGES):
        wa_path.write_text(json.dumps(wa, indent=1, sort_keys=True) + "\n")
    wa = json.loads(wa_path.read_text())
    lines = []
    for ds, title in (("challenge", "Synthetic challenge (2,893 labelled rows)"), ("dev24", "Real development sample, T1 24 h (102 events)"),
                      ("dev6", "Real development sample, T1b 6 h (159 events)")):
        lines += [f"### Approaches: {title}", "",
                  "| Approach | Venv | Folds | OOS N | Positives | Brier | B0 Brier, same rows | BSS vs B0 | Log loss | Mean p | Observed | Mean p in Wilson 95% | Fold audit | Wall s | CPU s | Peak MB | Same output, 3 runs |",
                  "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|---|---:|---:|---:|---|"]
        for k in sorted(r["approaches"][ds]):
            x = r["approaches"][ds][k]
            m = x["metrics"]
            ap, venv = k.split("__")
            lines.append(f"| {ap} | {venv} | {m.get('folds')} | {m.get('n_oos')} | {m.get('positives_oos')} | {m.get('brier')} | "
                         f"{m.get('brier_b0_same_rows')} | {m.get('bss_vs_b0')} | {m.get('log_loss')} | {m.get('mean_p')} | {m.get('observed_rate')} | "
                         f"{'yes' if m.get('mean_p_inside_wilson95') else 'no'} | {'valid' if m.get('fold_audit_valid') else 'INVALID'} | "
                         f"{x['wall_median_s']} | {x['cpu_median_s']} | {x['peak_rss_max_mb']} | {'yes' if x['identical_output_three_runs'] else 'NO'} |")
        lines.append("")
    lines += ["### Cold start (import in a fresh process, median of 5, offline)", "",
              "| Component | Modules imported | Interpreter | Wall s | CPU s | Peak MB | Socket events | Heavy modules loaded |",
              "|---|---|---|---:|---:|---:|---:|---|"]
    for k, x in sorted(r["imports"].items(), key=lambda kv: kv[1]["wall_median_s"]):
        loaded = x["loaded"]
        mods = loaded.split(" | ")[0].removeprefix("imported ")
        heavy = loaded.split("heavy modules loaded: ")[1].split(" |")[0] if "heavy modules loaded: " in loaded else ""
        venv = x["python"].split("/venvs/")[1].split("/")[0] if "/venvs/" in x["python"] else "system 3.13"
        lines.append(f"| {k} | `{mods}` | {venv} | {x['wall_median_s']} | {x['cpu_median_s']} | {x['peak_rss_max_mb']} | {x['net_events_total']} | {heavy or 'none'} |")
    lines += ["", "### Wheels for CPython 3.13 at the exact version (PyPI file lists)", "",
              "| Package | Requires Python | Linux x86_64 | Windows x86_64 | macOS arm64 | Note |", "|---|---|---|---|---|---|"]
    for k, v in wa.items():
        note = "sdist only: refused by the install route" if v["sdist_only"] else ""
        lines.append(f"| {k} | {v['requires_python']} | {'yes' if v['linux'] else 'no'} | {'yes' if v['windows'] else 'no'} | "
                     f"{'yes' if v['macos_arm64'] else 'no'} | {note} |")
    lines += ["", "### Component checks (cost and reproducibility)", "",
              "| Check | Wall s | CPU s | Peak MB | Socket events | Same output, 3 runs | Exit 0 |", "|---|---:|---:|---:|---:|---|---|"]
    for k, x in r["checks"].items():
        lines.append(f"| {k} | {x['wall_median_s']} | {x['cpu_median_s']} | {x['peak_rss_max_mb']} | {x['net_events_total']} | "
                     f"{'yes' if x['identical_output_three_runs'] else 'NO'} | {'yes' if x['all_exit_0'] else 'no (expected for mesa_plain_install)'} |")
    text = Path(md).read_text()
    head = text.split(MARK)[0].rstrip() + "\n\n" + MARK + "\n\n"
    Path(md).write_text(head + "\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
