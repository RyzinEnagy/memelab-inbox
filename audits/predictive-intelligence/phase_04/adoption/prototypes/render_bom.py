"""Phase 04: render the bill-of-materials tables of BOM_LOCKS.md from the BOM JSON files written by build_lock.py.
Tables only; the narrative is in BOM_LOCKS.md above the marker line, which this script keeps.

    python render_bom.py BOM_LOCKS.md evidence/research-py313.bom.json evidence/core-py313.bom.json
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

MARK = "<!-- tables below are generated by prototypes/render_bom.py; do not edit by hand -->"


def table(bom: dict, title: str) -> str:
    out = [f"### {title}", "", "| Package | Version | Declared license | Requires Python | Linux x86_64 wheel | Windows x86_64 wheel | macOS arm64 wheel |",
           "|---|---|---|---|---|---|---|"]
    for p in bom["packages"]:
        cells = []
        for plat in ("linux_x86_64", "win_amd64", "macos_arm64"):
            ws = [w for w in p["wheels"] if plat in w["platforms"]]
            cells.append("<br>".join(f"`{w['file']}`<br>sha256 `{w['sha256']}`" for w in ws) or "none")
        out.append(f"| {p['name']} | {p['version']} | {p['license_declared'] or 'not declared'} | {p['requires_python'] or 'not declared'} | "
                   + " | ".join(cells) + " |")
    return "\n".join(out) + "\n"


def main(md: str, *boms: str) -> None:
    text = Path(md).read_text()
    head = text.split(MARK)[0].rstrip() + "\n\n" + MARK + "\n\n"
    parts = []
    for b in boms:
        d = json.loads(Path(b).read_text())
        name = Path(b).name.replace(".bom.json", "")
        parts.append(table(d, f"`{name}.txt` ({len(d['packages'])} packages, {sum(len(p['wheels']) for p in d['packages'])} wheel hashes)"))
    Path(md).write_text(head + "\n".join(parts))


if __name__ == "__main__":
    main(sys.argv[1], *sys.argv[2:])
