def jl(p):
    return [json.loads(l) for l in open(p) if l.strip()]


def main(argv):
    base = argv[1]
    R = os.path.join(base, "research")
    q = jl(os.path.join(R, "QUERY_RESULTS.jsonl"))
    p = jl(os.path.join(R, "PYPI_LOOKUPS.jsonl"))
    cands = list(csv.DictReader(open(os.path.join(R, "CANDIDATES.csv"))))
    short = list(csv.DictReader(open(os.path.join(R, "SHORTLIST.csv"))))
    audit = json.load(open(os.path.join(R, "PROVENANCE_AUDIT.json")))
    needs_sha = hashlib.sha256(open(os.path.join(R, "NEEDS.csv"), "rb").read()).hexdigest()
    credited = defaultdict(list)
    for c in cands:
        for qid in c["discovery_qids"].split(";"):
            key = qid.split(">")[0]
            credited[key].append(c["canonical_repo"])
    ok = [r for r in q if r["mechanism"] != "GITHUB_SEARCH_API"]
    distinct_ok = {(r["mechanism"], r.get("query") or r.get("url")) for r in ok}
    mech = Counter(r["mechanism"] for r in q)
    text = HEAD.format(needs_sha=needs_sha, n_gh=mech["GITHUB_SEARCH_API"], n_k=mech["PACKAGE_KEYWORD_INDEX"],
                       n_kw=len({r.get("query") for r in q if r["mechanism"] == "PACKAGE_KEYWORD_INDEX"}),
                       n_d=mech["DOCS_CROSSLINK"], n_a=mech["PAPER_LINK"],
                       n_a_gh=sum(1 for r in q if r["mechanism"] == "PAPER_LINK" and r.get("returned")), n_w=mech["WEBSEARCH"], n_p=len(p),
                       n_ok=len(distinct_ok), n_fam=len({r["family"] for r in ok}),
                       n_mech=len({r["mechanism"] for r in ok}) + (1 if p else 0))
    rows = []
    for r in q:
        what = r.get("query") or ""
        if r["mechanism"] in ("DOCS_CROSSLINK", "PAPER_LINK"):
            what = "%s (%s)" % (r.get("query"), r.get("url"))
        cr = sorted(set(credited.get(r["qid"], [])))
        rows.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
            r["qid"], r["mechanism"], r["family"], what.replace("|", "/"), r["retrieved_at"],
            r.get("http_status") if r.get("http_status") is not None else "n/a", r.get("returned", 0),
            (r.get("body_sha256") or "n/a")[:12], ("%d: %s" % (len(cr), ", ".join(cr))) if cr else "0"))
    weak = sum(1 for c in cands if all(x.startswith(("PYPI:", "SEED")) for x in c["discovery_qids"].split(";")))
    roots = set()
    hist = 0
    for c in cands:
        rs = set(c["root_commits"].split(";"))
        if not (rs & roots):
            hist += 1
        roots |= rs
    audit_rows = "\n".join("| `%s` | %s | %s | %s |" % (r["repo"], r["qid"], r["original_ranks"], r["rerun_ranks"]) for r in audit["rows"])
    n_verify = sum(1 for l in open(os.path.join(R, "VERIFY_RESULTS.jsonl")) if l.strip())
    tail = TAIL.format(n_cand=len(cands), n_hist=hist, n_verify=n_verify,
                       n_free=sum(1 for c in cands if c.get("independent_discovery_qids")),
                       n_free_orig=sum(1 for c in cands[:107] if c.get("independent_discovery_qids")),
                       n_indep=len(cands) - weak, n_seed=sum(1 for c in cands if c["in_package_seeds"] == "yes"),
                       n_short=len(short),
                       fam_counts=", ".join("%s %d" % kv for kv in sorted(Counter(c["family"] for c in cands).items())),
                       short_fams=", ".join("%s %d" % kv for kv in sorted(Counter(s["family"] for s in short).items())),
                       n_p=len(p), n_weak=weak, pop=audit["population_size"], audit_rows=audit_rows)
    open(os.path.join(R, "SEARCH_LOG.md"), "w").write(text + "\n".join(rows) + "\n" + tail)
    print("rows", len(rows), "distinct ok queries", len(distinct_ok), "families", len({r['family'] for r in ok}))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
